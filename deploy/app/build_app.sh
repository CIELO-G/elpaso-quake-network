#!/usr/bin/env bash
# Build "El Paso Monitor.app" — a thin macOS app over the existing conda env.
#
# The bundle just launches `python -m dashboard --app` from this repo with
# the elpaso-quake env's Python. Rebuild after moving the repo or recreating
# the env:
#
#   ./deploy/app/build_app.sh                # installs to /Applications
#   ./deploy/app/build_app.sh ~/Applications # or anywhere else

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
DEST="${1:-/Applications}"
APP="$DEST/El Paso Monitor.app"

PYTHON="$(conda run -n elpaso-quake python -c 'import sys; print(sys.executable)')"
# <conda_root>/envs/<env>/bin/python -> <conda_root>
CONDA_BASE="$(dirname "$(dirname "$(dirname "$(dirname "$PYTHON")")")")"
echo "Repo:   $REPO"
echo "Python: $PYTHON"
echo "Conda:  $CONDA_BASE"

# ── Remote-access credentials (kept OUT of git) ───────────────────────
# deploy/app/local.env is gitignored and holds DASHBOARD_USERNAME/PASSWORD.
# If present, the app binds 0.0.0.0 so browsers on the tailnet/LAN can
# connect (they get a login prompt; the local window never does). If
# absent, one is generated on first build so rebuilds keep the same
# password. Delete local.env and rebuild to rotate it.
LOCAL_ENV="$HERE/local.env"
if [ ! -f "$LOCAL_ENV" ]; then
    echo "Generating remote-access credentials -> $LOCAL_ENV"
    umask 177
    cat > "$LOCAL_ENV" <<CREDS
DASHBOARD_USERNAME=marc
DASHBOARD_PASSWORD=$(openssl rand -base64 18 | tr -d '/+=' | cut -d- -f1 | cut -c1-20)
# Alerts — fill in one or both, then rebuild the app:
#ALERT_EMAIL_TO=you@example.edu
#ALERT_EMAIL_FROM=you@example.edu
#ALERT_SMTP_HOST=smtp.gmail.com
#ALERT_SMTP_PORT=465
#ALERT_SMTP_PASSWORD=app-password
#ALERT_WEBHOOK_URL=https://hooks.slack.com/services/...
CREDS
    umask 022
fi
# shellcheck disable=SC1090
source "$LOCAL_ENV"
# Bind loopback only: remote access goes through `tailscale serve` (TLS,
# tailnet-only), so nothing listens on the LAN. See README Remote access.
HOST="127.0.0.1"

# ── Icon ──────────────────────────────────────────────────────────────
if [ ! -f "$HERE/AppIcon.icns" ]; then
    echo "Building icon..."
    "$PYTHON" "$HERE/make_icon.py"
    iconutil -c icns "$HERE/AppIcon.iconset" -o "$HERE/AppIcon.icns"
fi

# ── Bundle skeleton ───────────────────────────────────────────────────
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$HERE/AppIcon.icns" "$APP/Contents/Resources/AppIcon.icns"

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"
 "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key>            <string>El Paso Monitor</string>
    <key>CFBundleDisplayName</key>     <string>El Paso Monitor</string>
    <key>CFBundleIdentifier</key>      <string>org.elpaso.monitor</string>
    <key>CFBundleShortVersionString</key> <string>1.0</string>
    <key>CFBundlePackageType</key>     <string>APPL</string>
    <key>CFBundleExecutable</key>      <string>ElPasoMonitor</string>
    <key>CFBundleIconFile</key>        <string>AppIcon</string>
    <key>NSHighResolutionCapable</key> <true/>
</dict>
</plist>
PLIST

cat > "$APP/Contents/MacOS/ElPasoMonitor" <<LAUNCHER
#!/bin/bash
# Generated by deploy/app/build_app.sh — paths/credentials are baked in;
# rebuild to update (credentials come from deploy/app/local.env, gitignored).
cd "$REPO"
mkdir -p logs
# output/1-raw and output/2-processed may be symlinks to an external volume
# (RAID). At login that volume can mount after this app starts, so wait for
# it; never start the pipeline against a missing data volume.
for d in output/1-raw output/2-processed; do
    tries=0
    while [ ! -d "\$d/" ]; do
        tries=\$((tries + 1))
        if [ "\$tries" -gt 60 ]; then
            echo "\$(date -u '+%Y-%m-%d %H:%M:%S UTC') ABORT: \$d not reachable (data volume not mounted?)" >> logs/app.log
            osascript -e 'display alert "El Paso Monitor" message "The waveform data volume is not mounted. Mount the RAID and reopen the app."' >/dev/null 2>&1 || true
            exit 1
        fi
        sleep 5
    done
done
# Finder launches apps with a minimal PATH; give subprocesses the conda
# toolchain (detection resolves env pythons directly, but keep PATH sane
# for anything else that shells out).
export PATH="$(dirname "$PYTHON"):$CONDA_BASE/condabin:\$PATH"
export DASHBOARD_AUTH_ENABLED=1
export DASHBOARD_USERNAME='$DASHBOARD_USERNAME'
export DASHBOARD_PASSWORD='$DASHBOARD_PASSWORD'
export CARTO_BASEMAPS_KEY='${CARTO_BASEMAPS_KEY:-}'
# Alert channels (lib/monitoring.py). Empty = that channel is off; the
# dashboard's /api/health shows which are configured.
export ALERT_EMAIL_TO='${ALERT_EMAIL_TO:-}'
export ALERT_EMAIL_FROM='${ALERT_EMAIL_FROM:-}'
export ALERT_SMTP_HOST='${ALERT_SMTP_HOST:-}'
export ALERT_SMTP_PORT='${ALERT_SMTP_PORT:-}'
export ALERT_SMTP_PASSWORD='${ALERT_SMTP_PASSWORD:-}'
export ALERT_WEBHOOK_URL='${ALERT_WEBHOOK_URL:-}'
exec "$PYTHON" -m dashboard --app --host $HOST >> logs/app.log 2>&1
LAUNCHER
chmod 700 "$APP/Contents/MacOS/ElPasoMonitor"   # holds the dashboard password

echo "Built: $APP"
echo "Remote access: http://<this-mac's-tailscale-name-or-ip>:8000"
echo "  username: $DASHBOARD_USERNAME   password: (in $LOCAL_ENV)"
echo "Double-click it (or: open \"$APP\") to launch."
